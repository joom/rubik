#!/usr/bin/env python3
"""Generate facelet permutations from integer 3D quarter rotations.

Axes: +x right, +y up, +z front. Each face is viewed from outside;
rows run top to bottom, columns left to right. Clockwise is -90 degrees
about the outward normal. Only the outer layer rotates; centers stay fixed.
"""

import argparse
from pathlib import Path

# Each face supplies its outward normal, rightward axis, and downward axis.
FACES = {
    "Up": ((0, 1, 0), (1, 0, 0), (0, 0, 1)),
    "Right": ((1, 0, 0), (0, 0, -1), (0, -1, 0)),
    "Front": ((0, 0, 1), (1, 0, 0), (0, -1, 0)),
    "Down": ((0, -1, 0), (1, 0, 0), (0, 0, -1)),
    "Left": ((-1, 0, 0), (0, 0, 1), (0, -1, 0)),
    "Back": ((0, 0, -1), (-1, 0, 0), (0, -1, 0)),
}
START = "(* BEGIN GENERATED MOVES *)"
END = "(* END GENERATED MOVES *)"


def dot(a, b):
    """Project a position onto a face normal to identify its outer layer."""
    return sum(x * y for x, y in zip(a, b))


def rotate(v, n):
    """Rotate clockwise about the signed unit axis n using the cross product."""
    cross = (
        n[1] * v[2] - n[2] * v[1],
        n[2] * v[0] - n[0] * v[2],
        n[0] * v[1] - n[1] * v[0],
    )
    return tuple(n[i] * dot(n, v) - cross[i] for i in range(3))


def triple(xs):
    """Render three Rocq expressions as one reusable triple constructor."""
    return "(Triple " + " ".join(xs) + ")"


def pack(xs, indent):
    """Lay out the 54 stickers as six aligned grids in the state's face order."""
    grids = [
        triple([triple(xs[i + j:i + j + 3]) for j in (0, 3, 6)])
        for i in range(0, 54, 9)
    ]
    rows = "\n" + " " * (indent + 3)
    return (
        "(Triple" + rows + rows.join(grids[:3]) + ",\n"
        + " " * (indent + 1) + "Triple" + rows + rows.join(grids[3:]) + ")"
    )


def facelets():
    """Enumerate sticker positions and normals in outside-view row-major order."""
    return [
        (
            tuple(normal[i] + col * right[i] + row * down[i] for i in range(3)),
            normal,
        )
        for normal, right, down in FACES.values()
        for row in (-1, 0, 1)
        for col in (-1, 0, 1)
    ]


def generate():
    """Derive the six permutations and render the documented quarter-turn definition."""
    stickers = facelets()
    names = [f"{face[0].lower()}{i}" for face in FACES for i in range(9)]
    lines = [
        "(* Generated by scripts/generate_moves.py; checked against Geometry.v. *)",
        "(** A clockwise outer-layer turn permutes stickers while keeping centers fixed. *)",
        "Definition quarter (f : face) (s : state) : state :=",
        "  match s with",
        "  | " + pack(names, 4) + " =>",
        "    match f with",
    ]
    for face, (normal, _, _) in FACES.items():
        output = [None] * len(stickers)
        for name, (position, direction) in zip(names, stickers):
            target = (position, direction)
            if dot(position, normal) == 1:
                target = (rotate(position, normal), rotate(direction, normal))
            output[stickers.index(target)] = name
        assert sorted(output) == sorted(names)
        lines.extend([f"    | {face} =>", "      " + pack(output, 6)])
    return "\n".join([*lines, "    end", "  end.", ""])


def main():
    """Update only the generated region, or check that it is already reproducible."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if the checked-in tables are stale"
    )
    args = parser.parse_args()
    path = Path(__file__).resolve().parent.parent / "BasicRubik.v"
    source = path.read_text()
    before, rest = source.split(START, 1)
    _, after = rest.split(END, 1)
    updated = before + START + "\n" + generate() + END + after
    if args.check:
        if updated != source:
            raise SystemExit(
                "BasicRubik.v move tables are stale; run scripts/generate_moves.py"
            )
    else:
        path.write_text(updated)


if __name__ == "__main__":
    main()
